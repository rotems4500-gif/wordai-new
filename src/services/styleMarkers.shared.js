// ── 3. עזרים טהורים ────────────────────────────────────────────────────────

/** בריחה של תווי regex. רווח נשאר רווח ממשי (המקור מפריד במילים ברווח יחיד). */
export const escapeRegexLiteral = (text) => String(text || '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** `a|b|c` מוברח — לשיבוץ בתוך תבנית גדולה יותר. */
export const buildAlternation = (list) => (Array.isArray(list) ? list : [])
  .map(escapeRegexLiteral)
  .join('|');

/**
 * regex של חלופה מלאה מרשימת מחרוזות.
 * ⚠️ סדר החלופות אינו משנה כאן: הרשימות הן חסרות-תחיליות (אף פריט אינו תחילית של
 * אחר), ובכל מקרה מנוע ה-regex חוזר אחורה אם ההמשך אינו מתאים.
 */
export const buildAlternationRegex = (list, flags = '') => new RegExp(`(?:${buildAlternation(list)})`, flags);

/**
 * דוגמאות לפרומפט. ראש הרשימות הקנוניות הוא הליבה המקורית שנאספה ידנית (הזנב הוא
 * תוספות אימון), ולכן חיתוך מהראש נותן דוגמאות מייצגות — ובלי לנפח את הפרומפט
 * ל-40 פריטים. הפרומפט מקבל **דוגמאות**, הגלאי מקבל את הרשימה המלאה.
 */
export const markerExamples = (list, count) => (Array.isArray(list) ? list : []).slice(0, count);

/** אותו דבר, כבר מוכן לשיבוץ במחרוזת פרומפט: "א", "ב", "ג" */
export const markerExamplesQuoted = (list, count) => markerExamples(list, count)
  .map((phrase) => `"${phrase}"`)
  .join(', ');
