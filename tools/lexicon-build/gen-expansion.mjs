import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import {
  HEBREW_WORD_RE, STOP_WORDS, exists, sleep, normalizeLemmaKey, stripJsonFences,
  resolveGeminiApiKey, callGemini,
} from '../synonyms-build/lib.mjs';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(DIR, 'wordlists');
const argv = process.argv.slice(2);
const OUT_PATH = (() => {
  const i = argv.indexOf('--out');
  return i !== -1 ? argv[i + 1] : path.join(OUT_DIR, 'expansion-1.txt');
})();
const CHECKPOINT_PATH = path.join(DIR, 'gen-expansion-checkpoint.json');

const CATEGORIES = [
  'פעלים בכתיבה עיונית ומחקרית', 'שמות עצם מופשטים', 'שמות תואר אקדמיים',
  'פסיכולוגיה קוגניטיבית והתפתחותית', 'פסיכופתולוגיה וטיפול', 'סוציולוגיה ואנתרופולוגיה',
  'מדעי המדינה ומדיניות ציבורית', 'משפט חוקתי ומנהלי', 'משפט פרטי — חוזים ונזיקין',
  'כלכלה מיקרו ומקרו', 'מנהל עסקים ושיווק', 'חשבונאות ומימון',
  'חינוך — תיאוריות למידה', 'חינוך מיוחד והכלה', 'עבודה סוציאלית',
  'בריאות הציבור ואפידמיולוגיה', 'רפואה קלינית — מונחים בעברית', 'סיעוד ומקצועות הבריאות',
  'היסטוריה של עם ישראל', 'היסטוריה כללית מודרנית', 'מקרא ומחשבת ישראל',
  'ספרות ותורת הספרות', 'בלשנות ולשון עברית', 'פילוסופיה ואתיקה',
  'תקשורת המונים ומדיה חדשה', 'קולנוע ואמנות', 'מוזיקולוגיה',
  'גיאוגרפיה ולימודי סביבה', 'ביולוגיה ומדעי החיים', 'כימיה ופיזיקה — מונחים בעברית',
  'מדעי המחשב ומערכות מידע', 'סטטיסטיקה ושיטות מחקר כמותיות', 'שיטות מחקר איכותניות',
  'קרימינולוגיה ומשפט פלילי', 'יחסים בינלאומיים וביטחון', 'לימודי מגדר',
  'כלכלת ישראל וחברה ישראלית', 'ארגון וניהול משאבי אנוש', 'התנהגות ארגונית',
  'תזונה ומדעי המזון',
];
const LAYERS = [
  'מילים שכיחות שכל סטודנט פוגש בשנה הראשונה',
  'שכבה שנייה: מילים שמופיעות במאמרים אקדמיים אך אינן בסיסיות',
  'שכבה שלישית: מונחים ומילים נדירות יותר שמרצים ומחברי מאמרים משתמשים בהם',
];

function buildPrompt(category, layer) {
  return `תחום: "${category}". רמה: ${layer}.
צור רשימה של 80 לממות עבריות (צורות בסיס): פעלים בעבר נסתר, שמות עצם ביחיד,
שמות תואר בזכר יחיד. עברית בלבד, בלי ניקוד, בלי שמות פרטיים, בלי ראשי תיבות,
בלי מילים לועזיות בתעתיק אלא אם הן שגורות בכתיבה אקדמית עברית.
החזר אך ורק JSON: מערך שטוח של מחרוזות.`;
}

async function main() {
  const { key: apiKey, source } = await resolveGeminiApiKey();
  if (!apiKey) { console.error('No Gemini API key.'); process.exit(1); }
  console.log(`API key ✓ (${source}) — ${CATEGORIES.length} categories × ${LAYERS.length} layers`);

  await mkdir(OUT_DIR, { recursive: true });

  // checkpoint: קריאות שהושלמו + המילים שנאספו
  let state = { done: [], words: [] };
  if (await exists(CHECKPOINT_PATH)) {
    try { state = JSON.parse(await readFile(CHECKPOINT_PATH, 'utf8')); } catch {}
  }
  const doneSet = new Set(state.done);
  const collected = new Set(state.words);

  for (let ci = 0; ci < CATEGORIES.length; ci += 1) {
    for (let li = 0; li < LAYERS.length; li += 1) {
      const id = `${ci}_${li}`;
      if (doneSet.has(id)) continue;
      try {
        const text = await callGemini(apiKey, buildPrompt(CATEGORIES[ci], LAYERS[li]));
        const arr = JSON.parse(stripJsonFences(text));
        let added = 0;
        if (Array.isArray(arr)) {
          for (const w0 of arr) {
            const w = normalizeLemmaKey(w0);
            if (w && HEBREW_WORD_RE.test(w) && w.length >= 2 && !STOP_WORDS.has(w) && !collected.has(w)) {
              collected.add(w);
              added += 1;
            }
          }
        }
        console.log(`[${id}] ${CATEGORIES[ci].slice(0, 25)}… L${li + 1}: +${added} (total ${collected.size})`);
      } catch (e) {
        console.warn(`[${id}] failed: ${e.message}`);
      }
      doneSet.add(id);
      await writeFile(CHECKPOINT_PATH, JSON.stringify({ done: [...doneSet], words: [...collected] }), 'utf8');
      await sleep(1000);
    }
  }

  const sorted = [...collected].sort();
  await writeFile(OUT_PATH, `# generated by gen-expansion.mjs — ${sorted.length} words\n${sorted.join('\n')}\n`, 'utf8');
  console.log(`\nwritten: ${OUT_PATH} (${sorted.length} words)`);
  console.log(`next: node tools/lexicon-build/build.mjs --expand-only --wordlist "${OUT_PATH}"`);
}

main().catch((e) => { console.error('fatal:', e); process.exit(1); });
