// הטריק: פרומפטים "שכבתיים" — לכל תחום מבקשים במפורש את השכבה שמעבר לבסיסית
// ("מילים שסטודנט שנה ג' פוגש, לא המילים הראשונות שכולם יודעים"), בשלוש רמות.
//   node tools/lexicon-build/gen-expansion.mjs [--out FILE]
// פלט: tools/lexicon-build/wordlists/expansion-1.txt (מילה בשורה, ממוין, ייחודי)
// ואז:  node tools/lexicon-build/build.mjs --expand-only --wordlist <FILE>
